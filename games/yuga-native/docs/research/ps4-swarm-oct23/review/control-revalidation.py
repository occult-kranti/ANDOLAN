#!/usr/bin/env python3
"""Revalidate cleanup boundaries with disposable local Git fixtures only."""
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import tempfile
from unittest import mock

HERE = Path(__file__).resolve().parent
SOURCE = Path('/workspace/ANDOLAN/games/yuga-native/tools/local-swarm/control.py')
spec = importlib.util.spec_from_file_location('control_review_fixed', SOURCE)
helper = importlib.util.module_from_spec(spec)
spec.loader.exec_module(helper)


def git(root, *args):
    return subprocess.run(['git', '-C', str(root), *args], check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True).stdout.strip()


def packet(root, file):
    return {'schema_version': 1, 'operation': 'quarantine',
            'generated_roots': ['scratch/generated'],
            'files': [{'path': str(file.relative_to(root)), 'classification': 'generated',
                       'bytes': file.stat().st_size,
                       'sha256': hashlib.sha256(file.read_bytes()).hexdigest()}]}


def blocked(root, file):
    try:
        helper.plan_cleanup(packet(root, file), root)
    except helper.ControlError as error:
        return {'blocked': True, 'reason': str(error), 'file_preserved': file.exists()}
    return {'blocked': False, 'file_preserved': file.exists()}


results = {}
with tempfile.TemporaryDirectory(prefix='nested-git-fixed-') as temporary:
    root = Path(temporary).resolve()
    git(root, 'init', '--quiet')
    nested = root / 'scratch/generated/component'
    nested.mkdir(parents=True)
    git(nested, 'init', '--quiet')
    file = nested / 'asset.bin'
    file.write_bytes(b'tracked source artifact')
    git(nested, 'add', 'asset.bin')
    git(nested, '-c', 'user.name=Review Fixture', '-c',
        'user.email=review@example.invalid', 'commit', '--quiet', '-m', 'fixture')
    results['untracked_nested_repository'] = blocked(root, file)
    git(root, 'add', 'scratch/generated/component')
    results['tracked_gitlink'] = blocked(root, file)
    separate = root / 'scratch/generated/worktree'
    separate.mkdir()
    (separate / '.git').write_text('gitdir: /does-not-need-to-exist-for-boundary-check\n')
    worktree_file = separate / 'asset.bin'
    worktree_file.write_bytes(b'worktree source')
    results['nested_git_file'] = blocked(root, worktree_file)
    ordinary = root / 'scratch/generated/cache.bin'
    ordinary.write_bytes(b'disposable generated bytes')
    with mock.patch.object(helper, 'tracked_paths', return_value={'SCRATCH/GENERATED/CACHE.BIN'}):
        results['casefold_tracked_identity'] = blocked(root, ordinary)
    # The result intentionally omits classification from a validated plan.
    plan = helper.plan_cleanup(packet(root, ordinary), root)
    results['ordinary_generated_file'] = {'accepted': len(plan) == 1 and plan[0]['path'] == str(ordinary.relative_to(root)),
                                          'file_preserved': ordinary.exists()}

checks_passed = all(value['blocked'] and value['file_preserved'] for key, value in results.items()
                    if key != 'ordinary_generated_file')
checks_passed = checks_passed and results['ordinary_generated_file']['accepted']
report = {'status': 'PASS' if checks_passed else 'FAIL',
          'source_path': str(SOURCE), 'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
          'checks': results, 'network_requests': 0, 'quarantine_executed': False,
          'windows_native_run': False,
          'casefold_check_scope': 'synthetic differently cased tracked-name input on Linux'}
(HERE / 'control-revalidation.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
raise SystemExit(0 if checks_passed else 1)
