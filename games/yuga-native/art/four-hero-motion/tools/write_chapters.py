"""Export frame-accurate film navigation for the standalone HTML gallery."""

import json
from pathlib import Path

PACK = Path(__file__).resolve().parents[1]
VIDEO = PACK / "media/video"


def stamp(seconds):
    milliseconds = round(seconds * 1000)
    hrs, remainder = divmod(milliseconds, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    secs, ms = divmod(remainder, 1000)
    return f"{hrs:02}:{minutes:02}:{secs:02}.{ms:03}"


def webvtt(name, chapters):
    cues = ["WEBVTT", ""]
    for cb in chapters:
        cues += [f'{stamp(cb["start"])} --> {stamp(cb["end"])}', cb["title"], ""]
    (VIDEO / f"{name}.vtt").write_text("\n".join(cues) + "\n")


def main():
    shots = json.loads((PACK / "tools/render/shots.json").read_text())
    fps = shots["fps"]
    guides = {}
    for hero, plan in shots["heroes"].items():
        t = 0
        chapters = []
        for shot in plan["shots"]:
            chapters.append(
                {
                    "title": shot["label"],
                    "start": t / fps,
                    "end": (t + shot["frames"]) / fps,
                }
            )
            t += shot["frames"]
        receipt = VIDEO / f"{hero}.json"
        if receipt.exists():
            render = json.loads(receipt.read_text())
            assert [s["start_frame"] for s in render["shots"]] == [
                round(c["start"] * fps) for c in chapters
            ]
            assert t == render["total_frames"] and fps == render["fps"]
        guides[hero] = chapters
    edit = json.loads((PACK / "evidence/animatic.json").read_text())
    cuts = edit["timeline"]
    guides["signature-animatic"] = [
        {
            "title": section["ability"],
            "start": section["overview_start"] / edit["fps"],
            "end": (
                cuts[i + 1]["overview_start"] if i + 1 < len(cuts) else edit["frames"]
            )
            / edit["fps"],
        }
        for i, section in enumerate(cuts)
    ]
    for name, chapters in guides.items():
        webvtt(name, chapters)
    js = "// Generated by tools/write_chapters.py from the editorial frame lists.\n"
    (PACK / "chapters.js").write_text(
        js
        + "window.yugaChapters = "
        + json.dumps(guides, indent=2, ensure_ascii=False)
        + ";\n"
    )


if __name__ == "__main__":
    main()
